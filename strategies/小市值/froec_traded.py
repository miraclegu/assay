def initialize(context):
    # getattr 保底：--param 显式指定时仍然生效，不被本版默认值覆盖。
    g.paused_in_pool = getattr(g, 'paused_in_pool', 0)
    g.kcb_688_only = getattr(g, 'kcb_688_only', 0)
    # ---- 调仓改到每周第 2 个交易日（2026-09-01 实盘起）----
    # 换的是【相位】不是规则，所以先量噪声再改。2019-01-01~2026-08-31：
    #   全程年化   周一 52.90 / 周二 55.90 / 周三 54.85 / 周四 43.04 / 周五 46.47
    #              -> 跨度 12.86pp，同一套规则只因星期不同
    #   逐年独立   周二 - 周一 = [-5.4,+5.7,+13.8,-13.2,-3.4,+20.4,+9.3,+22.6]
    #              均值 +6.21pp，周二胜 5/8 年，t=1.38 p=0.211
    # 【p=0.211 不显著】—— 周二样本内略好，但不构成"周二更优"的证据，
    # 这是噪声带内的自由选择。改它的真实理由是实盘启动日是周二。
    # ★ 反过来说：froec 系列的年化数字自带 ±5pp 级的相位噪声，
    #   别把任何单一星期的回测值当成精确预期。
    # 想复现本文件 docstring 里那些【对标基线】，必须 --param weekday=1
    #   —— 那些数字全部是在周一档上测的。
    g.weekday = getattr(g, 'weekday', 2)
    _base.initialize(context)
