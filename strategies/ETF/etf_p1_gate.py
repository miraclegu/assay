def _wfill(members, info, gross):
    """反波动率定权 + **严格**执行 `W_CAP`（water-filling），总仓位上限 `gross`。

    🔴 原版 `_weights` 是「先 `min(raw, W_CAP)`、**再归一化到 GROSS**」——
      后一步把 cap 冲掉了：3 只时 cap 后各 0.20、和 0.60，
      再 ÷0.60×0.97 = **每只 0.323**。也就是说原版的 `W_CAP`
      在只数少时**完全没有约束力**，真正压住集中度的是闸门那个 `scale`。
      实测（降仓期 304 次）：现状单只最大权重均值 9.7%，
      而单纯去掉闸门（`gate=off`）立刻变成 **26.9%**、峰值 43.6%。
      ★ 所以 `off` 根本不是"同样持仓、只把总仓位升上去"，
        而是"把 97% 压在剩下的两三只上" —— 那 44% 的回撤是**集中度**
        炸出来的，不是"升仓位有害"。用户 2026-09-20 的质疑是对的。

    water-filling：超过 `W_CAP` 的钉在 cap 上，剩余预算在其余标的间
    按反波动率再分配，直到没有人超限。**只数不够就吃不满 `gross`** ——
    那正是这个函数与原版的分水岭（原版会强行摊满）。
    """
    if not members:
        return {}
    raw = {s: 1.0 / info[s]['vol'] for s in members}
    fixed, rest, budget = {}, set(members), gross
    for _ in range(len(members) + 1):
        tot = sum(raw[s] for s in rest)
        if not rest or tot <= 0 or budget <= 1e-12:
            break
        w = {s: raw[s] / tot * budget for s in rest}
        over = [s for s in w if w[s] > _p1.W_CAP + 1e-12]
        if not over:
            fixed.update(w)
            break
        for s in over:
            fixed[s] = _p1.W_CAP
            rest.discard(s)
            budget -= _p1.W_CAP
    return _p1._cap_cluster(fixed, _p1._cluster_map(list(fixed), info), info)


def _weights_fill(members, info, cand, gross):
    """在 `_wfill` 基础上：**只数不够就补标的**，直到能吃下 `gross`。

    用户 2026-09-20 的原话：「降仓期间的持仓也和现在相同、持仓相对份额
    相同、只是把总仓位升上去，**当仓位数量需要增加时，则相应的重新分配
    仓位**」。后半句是关键 —— 97% 要在 `W_CAP=0.20` 下放得进去，
    至少得有 5 只；降仓期平均只有 3.5 只，所以**必须补人**。

    ★ 老成员之间的**相对份额自动不变**：`_wfill` 里它们都是
      `raw_i / tot × budget`，补人只改 `tot`，比值不变
      （cap 钉住的那几只除外 —— 而补人正是为了让 cap 不再 binding）。
    ★ 补完**没让总仓位变大就撤回**（簇上限可能把同簇的新人压住），
      保证这个循环是单调的 —— 否则"补了人反而更空"而它不报错。
    """
    mem = list(members)
    w = _wfill(mem, info, gross)
    for s in cand:
        if sum(w.values()) >= gross - 1e-6 or len(mem) >= _p1.N_MAX:
            break
        if s in mem:
            continue
        w2 = _wfill(mem + [s], info, gross)
        if sum(w2.values()) <= sum(w.values()) + 1e-9:
            continue                     # 补了没用（多半被簇上限压住），撤回
        mem.append(s)
        w = w2
    return w, mem


def _reselect_gate(context, sd):
    """与原版逐行相同，只有最后那个闸门按 `g.gate` 分三支。"""
    pool = _p1._dynamic_pool(context, sd)
    if not pool:
        return
    info = _p1._signals(_p1._px(context, sd, pool, _p1.NEED_FULL))
    if not info:
        return
    in_trend = set(c for c, v in info.items() if v['in_trend'])
    rs = _p1._rs_ok(info)
    ranked = sorted([s for s in in_trend if s in rs],
                    key=lambda s: (-info[s]['mom'], s))
    members = _p1._select(list(g.target), ranked, info)
    w = _p1._weights(members, info)
    scale = min(1.0, len(in_trend) / (_p1.BREADTH_FRAC * _p1.POOL_N))
    nfill = 0
    if scale < 1.0:
        g.n_breadth += 1
        if g.gate in ('cap', 'fill'):
            # ★ 用户 2026-09-20 要的那个：**持仓不变、相对份额不变、
            #   只把总仓位升上去**。做得到的前提是先把 `W_CAP` 修成
            #   真的 cap（见 `_wfill` 的注释）——
            #     cap   只升到"在这个只数下放得进去"为止，不补人
            #     fill  只数不够就按候选链补人，直到吃满 GROSS
            if g.gate == 'cap':
                w = _wfill(members, info, _p1.GROSS)
            else:
                rest1 = [s for s in ranked if s not in members]
                rest2 = sorted([s for s in in_trend
                                if s not in rs and s not in members],
                               key=lambda s: (-info[s]['mom'], s))
                # 🔴 第三层是**不在势**的标的 —— 补它等于放弃趋势条件，
                #    所以单独一个开关，默认打开（不然降仓期物理上凑不满）。
                rest3 = (sorted([s for s in info if s not in in_trend
                                 and s not in members],
                                key=lambda s: (-info[s]['mom'], s))
                         if g.fill_src == 'pool' else [])
                w, mem2 = _weights_fill(members, info,
                                        rest1 + rest2 + rest3, _p1.GROSS)
                nfill = len(mem2) - len(members)
        elif g.gate == 'mask':
            # 用户 2026-09-20 第三问：「73.7% 以下单调亏损，为什么摘不掉？
            # 定然是摘除方式有问题」——**他是对的**。`flat`/`cut`/`zero` 都写
            # `w = {}`，而那触发了两件与「摘除」无关的事：
            #   ① `_is_reselect_day` 里的 `or (not g.target)` -> 空仓期**逐日重选**
            #   ② `_select(list(g.target), ...)` 拿不到上期 keys -> **缓冲汰换记忆被清空**
            # 所以那不是"纯摘除"，是"摘除 + 换了一套重选节奏与汰换记忆"。
            # 🔴 纯摘除 = **保留 keys、权重全置 0**：字典非空 -> 两条副作用都不触发，
            #    而 `_place` 在重选日会 order_target_value(code, 0) 真的清仓。
            if len(in_trend) < g.mask_below:
                w = {s2: 0.0 for s2 in w}
            else:
                w = {s2: x * scale for s2, x in w.items()}
        elif g.gate == 'zero':
            # 用户 2026-09-20：「in_trend 低于 15 或 10 时是不是可以直接空仓，
            # 无需逐步降仓」——按 **in_trend 阈值**清零（cut 是按仓位阈值，
            # 两者只是同一件事的两种参数化）。
            # 🔴 `zero_below=15` 必须与 `flat` **逐位相同**（scale<1 <=> n<15），
            #    那是这个实现对不对的自证。
            if len(in_trend) < g.zero_below:
                w = {}
            else:
                w = {s2: x * scale for s2, x in w.items()}
        elif g.gate == 'cut':
            # 用户 2026-09-20：「仓位实际要求降低到 70% 时，应该保持空仓」——
            # 即先按现状降仓，降完不到阈值就**清零**（flat 是它 cut_at=1.0 的极端版）。
            # 🔴 这是**用结果选规则**（看了哪几档赚钱才决定保留哪几档），
            #    而且清零会改变路径（同 flat：重选 589 -> 1413 次）。所以必须实测。
            w = {s2: x * scale for s2, x in w.items()}
            if sum(w.values()) < g.cut_at:
                w = {}
        elif g.gate == 'flat':
            w = {}                       # 降仓期直接空仓
        elif g.gate == 'off':
            pass                         # 不降，满仓给在势的那几只
        elif g.gate == 'floor':
            # ★ 数据指出来的第三条路：**给降仓设一个下限**。
            #   诊断发现 scale<0.2 那一档（83 次）之后中证500 反而
            #   **+0.476%、上涨 60%** —— 广度最差的时候恰恰是底部附近，
            #   那时几乎空仓是**反向**的。所以不让仓位掉到 floor 以下。
            w = {s: x * max(scale, g.gate_floor) for s, x in w.items()}
        else:
            w = {s: x * scale for s, x in w.items()}
    # ★ 记下来：没有它就回答不了"降仓期间赚还是亏"
    g.gate_log.append({'date': str(context.current_date), 'n': len(in_trend),
                       'scale': round(scale, 4),
                       'gross': round(sum(w.values()), 4),
                       # ★ 只数与单只最大权重 —— 用户 2026-09-20 的质疑
                       #   （"降仓期有收益，升仓位反而更差，肯定有地方不对"）
                       #   就是靠这两个数定位的：`off` 不是"同样持仓升总仓位"，
                       #   而是把 97% 压在剩下的两三只上。
                       'k': len(w), 'nfill': nfill,
                       'wmax': round(max(w.values()), 4) if w else 0.0})
    g.target = w


